"""
validate.py
===========

Run all validation checks on the delivered .cube and write
VALIDATION_REPORT.txt.

Checks performed (only tests actually run are documented):
  1. .cube structure: 33^3, syntax, line count, value range, no NaN/inf.
  2. Apple Log 2 decode vs published constants (18% grey -> 500/1023,
     round-trip encode/decode, constant cross-check).
  3. Apple Wide Gamut transform: white-preserving matrix, primaries
     cross-check, comparison to the published ASWF AppleWG->ACES matrix.
  4. Rec.709 gamma 2.4 output behaviour.
  5. Neutral behaviour (no colour cast on neutral grays).
  6. Tonal smoothness / monotonicity / clipping.
  7. Skin, sky, foliage behaviour (flat patches + scene regions).
  8. Simulated exposure levels (0.7x, 1.0x, 1.4x).
  9. AFTER renders reproduced from the delivered .cube.
"""

from __future__ import annotations

import io
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import color_science as cs
import grade
import scenes
from cube_io import read_cube, apply_cube, write_cube

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LUT_PATH = os.path.join(ROOT, "LUT", "GOLDEN_DAYLIGHT_CINEMA.cube")
REPORT_PATH = os.path.join(ROOT, "VALIDATION_REPORT.txt")
PREVIEWS = os.path.join(ROOT, "PREVIEWS")

AWG_TO_709 = cs.apple_wide_gamut_to_rec709()
OUT = []


def log(s=""):
    OUT.append(s)
    print(s)


def check(name, ok, detail=""):
    log(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" -- {detail}" if detail else ""))
    return ok


def main():
    log("=" * 78)
    log("GOLDEN DAYLIGHT CINEMA -- VALIDATION REPORT")
    log("=" * 78)
    log("Generated by scripts/validate.py (deterministic, reproducible).")
    log("")

    # ------------------------------------------------------------------ 1
    log("\n[1] .cube structure, syntax and numerical integrity")
    lut = read_cube(LUT_PATH)
    ok = True
    ok &= check("LUT_3D_SIZE == 33", lut["size"] == 33, f"size={lut['size']}")
    data = lut["data"]
    ok &= check("data shape == (33,33,33,3)", data.shape == (33, 33, 33, 3), str(data.shape))
    nlines = sum(1 for _ in open(LUT_PATH) if _.strip() and not _.strip().startswith("#")
                 and not _.strip().split()[0] in
                 ("TITLE", "LUT_3D_SIZE", "DOMAIN_MIN", "DOMAIN_MAX"))
    ok &= check("data line count == 33^3 (35937)", nlines == 35937, f"lines={nlines}")
    ok &= check("all values finite", np.isfinite(data).all())
    ok &= check("no NaN", not np.isnan(data).any())
    ok &= check("no +/-inf", not np.isinf(data).any())
    ok &= check("values within [0,1]", data.min() >= 0.0 and data.max() <= 1.0,
                f"range=[{data.min():.4f},{data.max():.4f}]")
    ok &= check("DOMAIN_MIN 0, DOMAIN_MAX 1",
                np.allclose(lut["domain_min"], 0) and np.allclose(lut["domain_max"], 1))
    ok &= check("TITLE present", bool(lut["title"]), lut["title"][:50])

    # ------------------------------------------------------------------ 2
    log("\n[2] Apple Log 2 decoding vs published references")
    ok2 = True
    # 18% grey should encode to 10-bit code value 500 -> 500/1023.
    v18 = cs.linear_to_apple_log(np.array([0.18, 0.18, 0.18]))
    ok2 &= check("18% grey encodes to ~500/1023", abs(v18[0] - 500 / 1023) < 0.005,
                 f"got {v18[0]:.5f}, expected {500/1023:.5f}")
    # Round-trip.
    xs = np.linspace(0.0, 1.0, 20001)
    rt = cs.apple_log_to_linear(cs.linear_to_apple_log(xs))
    mask = xs >= -0.05
    ok2 &= check("encode/decode round-trip", np.allclose(rt[mask], xs[mask], atol=1e-9),
                 f"max err {np.max(np.abs(rt[mask]-xs[mask])):.2e}")
    # Constants match published values.
    ok2 &= check("curve constants match Apple white paper",
                 abs(cs.APPLE_LOG_R_0 - -0.05641088) < 1e-8
                 and abs(cs.APPLE_LOG_C - 47.28711236) < 1e-8
                 and abs(cs.APPLE_LOG_GAMMA - 0.08550479) < 1e-8
                 and abs(cs.APPLE_LOG_DELTA - 0.69336945) < 1e-8)
    # White (linear 1.0) encodes to a known log value.
    vw = cs.linear_to_apple_log(np.array([1.0]))
    ok2 &= check("linear 1.0 encodes to ~0.69456", abs(vw[0] - 0.69456) < 0.001,
                 f"got {vw[0]:.5f}")

    # ------------------------------------------------------------------ 3
    log("\n[3] Apple Wide Gamut transformation")
    ok3 = True
    m = AWG_TO_709
    # White-preserving: neutrals map to neutrals.
    neutral = m @ np.array([1.0, 1.0, 1.0])
    ok3 &= check("matrix is white-preserving (neutral -> neutral)",
                 np.allclose(neutral, [1.0, 1.0, 1.0], atol=1e-9), str(neutral))
    # Row sums == 1.
    ok3 &= check("matrix row sums == 1", np.allclose(m.sum(axis=1), 1.0, atol=1e-9))
    # Primaries match Apple's published Apple Wide Gamut values.
    pwg = cs.APPLE_WIDE_GAMUT_PRIMARIES
    ok3 &= check("Apple Wide Gamut primaries match published values",
                 np.allclose(pwg, [(0.725, 0.301), (0.221, 0.814), (0.068, -0.076)], atol=1e-9))
    # Cross-check derivation vs published ASWF AppleWG->ACES2065-1 matrix.
    # Both derive from the same AppleWG primaries; the ACES path adds a
    # non-trivial adaptation. We report the relationship (see report text).
    derived_aces = cs.apple_wide_gamut_to_aces2065()
    pub_aces = cs.PUBLISHED_APPLEWG_TO_ACES
    log(f"      (info) derived AppleWG->ACES vs published ASWF matrix: "
        f"max|diff| = {np.max(np.abs(derived_aces - pub_aces)):.4f}")
    log("      The ACES reference applies an additional ACES-specific chromatic")
    log("      adaptation; our LUT uses the transparent white-preserving primaries")
    log("      matrix (standard for log->Rec.709 LUTs). Same source primaries.")

    # ------------------------------------------------------------------ 4
    log("\n[4] Rec.709 gamma 2.4 output")
    ok4 = True
    # Pure white in, white-ish out (tone-mapped, believable).
    white_in = np.array([[1.0, 1.0, 1.0]])
    white_out = grade.apple_log2_to_rec709_gamma24(white_in)[0]
    ok4 &= check("white input -> believable near-white output",
                 white_out.min() > 0.8 and white_out.max() <= 1.0,
                 f"out={np.round(white_out,3)}")
    # gamma 2.4 curve sanity: 0 -> 0, and monotonic.
    gs = np.linspace(0, 1, 500)
    go = cs.rec709_gamma24(gs)
    ok4 &= check("gamma 2.4 curve monotonic increasing", np.all(np.diff(go) >= 0))
    ok4 &= check("gamma 2.4: 0->0, 1->1", abs(go[0]) < 1e-9 and abs(go[-1] - 1) < 1e-9)

    # ------------------------------------------------------------------ 5
    log("\n[5] Neutral behaviour (no colour cast on neutrals)")
    ok5 = True
    grays = np.linspace(0.02, 0.95, 40)
    worst = 0.0
    for g in grays:
        inp = np.array([[g, g, g]])
        out = grade.apple_log2_to_rec709_gamma24(inp)[0]
        sat = (out.max() - out.min())
        worst = max(worst, sat)
    ok5 &= check("neutral grays stay near-neutral (max chroma small)", worst < 0.06,
                 f"max channel spread = {worst:.4f}")

    # ------------------------------------------------------------------ 6
    log("\n[6] Tonal smoothness, monotonicity and clipping")
    ok6 = True
    # Luminance ramp through the full pipeline; tone curve must be monotonic.
    ramp = np.linspace(0.0, 1.0, 4000)
    inp = np.stack([ramp, ramp, ramp], axis=1)
    out = grade.apple_log2_to_rec709_gamma24(inp)[:, 0]
    ok6 &= check("tone curve monotonic (no reversals)", np.all(np.diff(out) >= -1e-9))
    # No abrupt hard-clip plateaus at the top (smooth roll-off).
    top = out[-200:]
    ok6 &= check("highlight roll-off smooth (no hard clip)",
                 np.all(np.diff(top) >= -1e-9) and top[-1] <= 1.0,
                 f"top end={top[-1]:.4f}")
    # Shadow detail: in the real shadow region (above the below-black clip
    # threshold, log ~0.15), a luminance step must produce a proportional
    # output step (no hard clip / crushed blacks).  Below-black log values
    # correctly clip to 0 (that flat region is expected, not a defect).
    low = np.linspace(0.20, 0.45, 200)
    inp_low = np.stack([low, low, low], axis=1)
    out_low = grade.apple_log2_to_rec709_gamma24(inp_low)[:, 0]
    deriv = np.diff(out_low)
    ok6 &= check("shadow region smooth, detail preserved (no hard clip)",
                 deriv.min() > 0.0 and out_low[0] > 0.0,
                 f"min slope={deriv.min():.5f}, shadow out@0.20={out_low[0]:.4f}")

    # ------------------------------------------------------------------ 7
    log("\n[7] Skin / sky / foliage behaviour (flat patches)")
    ok7 = True
    # Reuse the patch set and measure hue/sat/light after the LUT.
    patches = {
        "skin":      (0.82, 0.62, 0.48),
        "sky":       (0.35, 0.55, 0.85),
        "sky_deep":  (0.20, 0.40, 0.75),
        "foliage":   (0.30, 0.55, 0.25),
        "stone":     (0.72, 0.66, 0.55),
        "white":     (0.95, 0.95, 0.93),
    }
    def to_srgb_linear(c):
        c = np.asarray(c, dtype=np.float64)
        return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)
    def hsl(rgb):
        r, g, b = rgb
        mx, mn = max(r, g, b), min(r, g, b)
        l = (mx + mn) / 2.0
        d = mx - mn
        if d == 0:
            return 0.0, 0.0, l
        s = d / (2 - mx - mn) if l > 0.5 else d / (mx + mn)
        if mx == r:
            h = (g - b) / d + (6 if g < b else 0)
        elif mx == g:
            h = (b - r) / d + 2
        else:
            h = (r - g) / d + 4
        return h * 60.0, s, l
    log(f"      {'patch':10} {'after(h,s,l)':>20}  target")
    for name, rgb in patches.items():
        lin = to_srgb_linear(rgb)
        lin_awg = lin @ np.linalg.inv(AWG_TO_709).T
        log2 = cs.linear_to_apple_log(lin_awg)
        out = apply_cube(lut, log2)
        h, s, l = hsl(out)
        log(f"      {name:10} ({h:6.1f},{s:.3f},{l:.3f})")
    # Target assertions (loose, behavioural).
    skin_lin = to_srgb_linear(patches["skin"]); skin_log = cs.linear_to_apple_log(skin_lin @ np.linalg.inv(AWG_TO_709).T)
    skin_out = apply_cube(lut, skin_log); sh, ss, sl = hsl(skin_out)
    ok7 &= check("skin hue in natural range (10-50deg)", 10 <= sh <= 50, f"hue={sh:.1f}")
    ok7 &= check("skin not over-saturated", ss < 0.55, f"sat={ss:.3f}")
    sky_lin = to_srgb_linear(patches["sky"]); sky_log = cs.linear_to_apple_log(sky_lin @ np.linalg.inv(AWG_TO_709).T)
    sky_out = apply_cube(lut, sky_log); syh, sys_, syl = hsl(sky_out)
    ok7 &= check("sky hue in blue range (180-260deg)", 180 <= syh <= 260, f"hue={syh:.1f}")
    fol_lin = to_srgb_linear(patches["foliage"]); fol_log = cs.linear_to_apple_log(fol_lin @ np.linalg.inv(AWG_TO_709).T)
    fol_out = apply_cube(lut, fol_log); fh, fs, fl = hsl(fol_out)
    ok7 &= check("foliage hue in green range (70-160deg)", 70 <= fh <= 160, f"hue={fh:.1f}")

    # ------------------------------------------------------------------ 8
    log("\n[8] Simulated exposure levels")
    ok8 = True
    fn = scenes.SCENES["scene1_midday_city"]
    srgb = fn()
    for exp in [0.7, 1.0, 1.4]:
        log2 = scenes.simulate_apple_log2(srgb, exposure=exp)
        out = apply_cube(lut, log2)
        finite = np.isfinite(out).all()
        inrange = out.min() >= 0.0 and out.max() <= 1.0
        log(f"      exposure {exp}x: log range [{log2.min():.3f},{log2.max():.3f}] "
            f"-> out range [{out.min():.4f},{out.max():.4f}] finite={finite} inrange={inrange}")
        ok8 &= check(f"exposure {exp}x handled (finite, in range)", finite and inrange)

    # ------------------------------------------------------------------ 9
    log("\n[9] AFTER renders reproduced from the delivered .cube")
    ok9 = True
    # Re-render one scene's AFTER directly from the .cube and compare to the
    # saved PNG (render.py used the same path; this confirms reproducibility).
    name = "scene4_beach_daylight"
    srgb = scenes.SCENES[name]()
    log2 = scenes.simulate_apple_log2(srgb, exposure=1.0)
    after = apply_cube(lut, log2)
    saved = np.asarray(Image.open(os.path.join(PREVIEWS, f"{name}_after.png"))).astype(np.float64) / 255.0
    # The saved PNG is uint8-quantised; allow quantisation tolerance.
    diff = np.abs(after - saved).max()
    ok9 &= check(f"{name} AFTER matches delivered .cube render", diff < 0.01,
                 f"max pixel diff = {diff:.4f} (uint8 quantisation)")
    # Also confirm BEFORE is the neutral decode (no grade).
    before_neutral = cs.rec709_gamma24(np.clip(cs.apple_log_to_linear(log2) @ AWG_TO_709.T, 0, None))
    saved_before = np.asarray(Image.open(os.path.join(PREVIEWS, f"{name}_before.png"))).astype(np.float64) / 255.0
    diffb = np.abs(before_neutral - saved_before).max()
    ok9 &= check(f"{name} BEFORE is neutral decode", diffb < 0.01, f"max diff = {diffb:.4f}")

    # ------------------------------------------------------------------ summary
    log("\n" + "=" * 78)
    all_ok = ok and ok2 and ok3 and ok4 and ok5 and ok6 and ok7 and ok8 and ok9
    log(f"OVERALL: {'ALL CHECKS PASSED' if all_ok else 'SOME CHECKS FAILED'}")
    log("=" * 78)

    text = "\n".join(OUT) + "\n"
    with open(REPORT_PATH, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"\nWrote {REPORT_PATH}")
    return all_ok


if __name__ == "__main__":
    ok = main()
    sys.exit(0 if ok else 1)

# ---------------------------------------------------------------------------
# 1.  NEUTRAL FILMIC TONE CURVE  (reflectance -> Rec.709 gamma 2.4 code)
# ---------------------------------------------------------------------------
# 18% grey lands on 0.430 code, a standard Rec.709 gamma-2.4 landing.
# 90% white card lands on 0.815: bright but still holding texture.
# 1200% (top of Apple Log 2) lands on 1.000 through a soft shoulder.
NEUTRAL_R = np.array([
    0.0000, 0.0010, 0.0027, 0.0056, 0.0112, 0.0225, 0.0450, 0.0900,
    0.1800, 0.3600, 0.5500, 0.7200, 0.9000, 1.2000, 1.8000, 2.7000,
    4.0000, 6.0000, 12.0000])
NEUTRAL_CODE = np.array([
    0.0000, 0.0022, 0.0130, 0.0290, 0.0530, 0.0960, 0.1760, 0.3000,
    0.4300, 0.5800, 0.6800, 0.7560, 0.8150, 0.8720, 0.9260, 0.9580,
    0.9780, 0.9910, 1.0000])

_P_NEUTRAL = np.clip(apple_log_encode(np.maximum(NEUTRAL_R, 0.0)), 0.0, 1.0)
_P_NEUTRAL[0] = 0.0
_TONE_P_TO_CODE = PchipInterpolator(_P_NEUTRAL, NEUTRAL_CODE, extrapolate=True)
_TONE_CODE_TO_P = PchipInterpolator(NEUTRAL_CODE, _P_NEUTRAL, extrapolate=True)


def neutral_code(lin709):
    """Scene-linear Rec.709 reflectance -> neutral Rec.709 g2.4 code."""
    lin = np.clip(np.asarray(lin709, dtype=np.float64), 0.0, 12.0)
    return np.clip(_TONE_P_TO_CODE(apple_log_encode(lin)), 0.0, 1.0)


def code_to_reflectance(code):
    """Inverse of neutral_code(), used to synthesise the log test plates."""
    c = np.clip(np.asarray(code, dtype=np.float64), 0.0, 1.0)
    return np.clip(apple_log_decode(np.clip(_TONE_CODE_TO_P(c), 0.0, 1.0)),
                   0.0, 12.0)


# ---------------------------------------------------------------------------
# 2.  GAMUT HANDLING
# ---------------------------------------------------------------------------
def softpos(x, rel=0.02):
    """C1, scale-invariant replacement for max(x, 0).

    Apple Wide Gamut is much wider than Rec.709, so the matrix routinely
    produces negative channels. Hard clipping at zero puts a slope kink into
    the transform, and a 33^3 LUT cannot represent a kink -- it smears it
    across a cell and shows up as hue blotches. The knee is relative to the
    pixel magnitude so the behaviour is self-similar across the 12 stops of
    scene-linear range (a fixed knee crushes shadows and does nothing for
    speculars).
    """
    x = np.asarray(x, dtype=np.float64)
    sc = np.abs(x).max(axis=-1, keepdims=True)
    kk = np.maximum(rel * sc, 1e-12)
    return x * smoothstep(0.0, kk, x)


def compress_negatives(rgb, knee=0.12, luma_floor=0.10):
    """Constant-luminance, constant-hue chroma reduction until min channel >= 0.

    The luma floor prevents the degenerate case where a saturated colour with
    near-zero Rec.709 luminance (e.g. a bright saturated blue) collapses to
    black, which would be a hard cliff in the LUT.
    """
    rgb = np.asarray(rgb, dtype=np.float64)
    mn = rgb.min(axis=-1)
    Y = rgb @ LUMA_709
    if luma_floor > 0.0:
        Y = np.maximum(Y, luma_floor * np.maximum(rgb.max(axis=-1), 0.0))
    den = Y - mn
    with np.errstate(divide='ignore', invalid='ignore'):
        s = np.where(den > 1e-9, Y / np.where(den > 1e-9, den, 1.0), 1.0)
    s = np.clip(np.where(np.isfinite(s), s, 1.0), 0.0, 1.0)
    with np.errstate(divide='ignore', invalid='ignore'):
        rel = np.clip(-mn / np.maximum(Y, 1e-4), 0.0, None)
    need = smoothstep(0.0, knee, np.where(np.isfinite(rel), rel, 0.0))
    comp = Y[..., None] + (rgb - Y[..., None]) * s[..., None]
    return rgb * (1.0 - need[..., None]) + comp * need[..., None]


def compress_gamut_out(rgb, hi=1.0, x0=0.96):
    """Chromaticity-preserving soft shoulder on the output side."""
    rgb = np.asarray(rgb, dtype=np.float64)
    mx = rgb.max(axis=-1)
    a = hi - x0
    mxc = np.where(mx <= x0, mx,
                   hi - a * np.exp(-np.maximum(mx - x0, 0.0) / a))
    with np.errstate(divide='ignore', invalid='ignore'):
        scale = np.where(mx > 1e-9, mxc / np.where(mx > 1e-9, mx, 1.0), 1.0)
    scale = np.clip(np.where(np.isfinite(scale), scale, 1.0), 0.0, 1.0)
    return rgb * scale[..., None]


# ---------------------------------------------------------------------------
# 3.  CREATIVE LOOK
# ---------------------------------------------------------------------------
# Hue angles are OkLab hue in degrees. Measured on the test scenes with
# dev/probe_scenes.py; skin sits near 50-65 deg, foliage 120-150 deg,
# midday sky 230-265 deg.
SKIN_H = 55.0
SKY_H = 250.0
FOLIAGE_H = 128.0
AMBER_H = 75.0

P = dict(
    # --- lightness -------------------------------------------------------
    s_k=0.48,                 # filmic S strength
    s_a=1.32,                 # sigmoid steepness
    s_toe_protect=0.22,       # code below which the S fades out
    s_toe_floor=0.45,         # S strength remaining at code 0
    level=0.974,              # global level trim (never brightens)
    mid_lift=0.014,           # low-midtone lift: stone/pavement stay luminous
    mid_lift_lo=0.10,
    mid_lift_hi=0.34,
    mid_lift_fade_lo=0.42,
    mid_lift_fade_hi=0.62,
    # --- chroma ----------------------------------------------------------
    chroma_mid=0.086,        # midtone saturation build
    chroma_shadow_keep=0.35,  # fraction of the build kept in deep shadow
    chroma_high_fade=0.55,   # how much chroma is pulled back near white
    skin_chroma=0.86,        # skin chroma multiplier (below 1 = held back)
    sky_chroma=1.06,
    foliage_chroma=1.02,
    # --- warmth ----------------------------------------------------------
    warm_a=0.0030,           # +red lean of the honey/amber split
    warm_b=0.0085,           # +yellow lean (the honey)
    warm_lo=0.10,            # lightness where warmth starts to build
    warm_hi=0.38,            # fully engaged
    warm_white_fade=0.55,    # fraction of warmth removed near pure white
    warm_b_sat=0.130,        # saturating b target: warmth fades as b approaches
    warm_a_sat=0.100,        # same for the red axis
    warm_chroma_damp=3.0,    # warmth is damped on already-chromatic pixels
    warm_skin_guard=0.20,    # extra damping inside the skin hue window
    shade_a=-0.0030,         # cool shadows (sun/shade separation)
    shade_b=-0.0022,
    shade_gain=1.30,
    # --- hue -------------------------------------------------------------
    sky_rot=+5.0,            # cyan -> blue, degrees at the sky hue
    sky_rot_lo=215.0,        # hue angle where the cyan pull is full
    sky_rot_hi=258.0,        # hue angle where the cyan pull has faded out
    foliage_rot=-4.0,        # yellow-green -> green
    skin_rot=+0.6,           # keep skin off the red axis
    # --- highlight handling ---------------------------------------------
    highlight_hold=0.55,     # chroma pulled from the top end
)

# Lightness curve. A true filmic S built analytically rather than from
# hand-drawn anchors: the normalised sigmoid s(x) = x^a / (x^a + (1-x)^a)
# is blended back toward the identity by `k`, weighted by `w` which protects
# the deepest shadows from being crushed. Endpoints are exact (0 -> 0, 1 -> 1),
# the mid slope is ~1.15 and the slope through the top two stops falls to ~0.6,
# which is what keeps highlight texture instead of clipping it.
S_K = 0.62          # strength of the S
S_A = 1.32          # sigmoid steepness
S_TOE_PROTECT = 0.10  # below this code the S is faded out
S_TOE_FLOOR = 0.35    # fraction of the S still applied at code 0


def _sigmoid_s(x, a=S_A):
    xa = np.power(np.clip(x, 1e-9, 1.0), a)
    ya = np.power(np.clip(1.0 - x, 1e-9, 1.0), a)
    return xa / (xa + ya)


def apply_lightness(L, params=None):
    """Display-referred lightness shaping (Rec.709 g2.4 code in and out)."""
    p = params if params is not None else P
    L = np.clip(np.asarray(L, dtype=np.float64), 0.0, 1.0)
    s = _sigmoid_s(L, p['s_a'])
    w = p['s_toe_floor'] + (1.0 - p['s_toe_floor']) * smoothstep(
        0.0, p['s_toe_protect'], L)
    out = L + p['s_k'] * w * (s - L)
    # The S alone deepens the low mids, which on warm stone and pavement reads
    # as muddy rather than rich. A bounded lift exactly in that band keeps
    # surfaces luminous while shadows and whites are untouched.
    out = out + p['mid_lift'] * smoothstep(p['mid_lift_lo'], p['mid_lift_hi'], L) \
        * (1.0 - smoothstep(p['mid_lift_fade_lo'], p['mid_lift_fade_hi'], L))
    # A gentle global level trim: midday footage must not be made brighter, so
    # the contrast build is compensated with a small, purely multiplicative drop
    # (multiplicative, not a pedestal, so deep shadows are not lifted or
    # flattened by it).
    out = out * p['level']
    return np.clip(out, 0.0, 1.0)


def _warm_gate(b, params):
    """How much of the warm push a pixel may receive, 0..1.

    The push SATURATES as the pixel's own yellow-blue balance approaches
    `warm_b_sat`. A neutral surface (b ~ 0) receives the full tint; a surface
    that is already strongly warm -- golden-hour sky, sunlit terracotta, a
    backlit meadow -- receives very little, because it is already there. This
    is the property that keeps golden-hour footage from doubling up, and unlike
    a flat multiplier it still lets honey limestone gain some warmth.
    """
    return 1.0 - smoothstep(0.0, params['warm_b_sat'], np.asarray(b, dtype=np.float64))


def gamut_fit_oklab(lab, iters=22, floor=0.0):
    """Bring an OkLab colour inside Rec.709 at CONSTANT lightness and hue.

    Chroma is scaled down by bisection until every linear Rec.709 channel is
    >= floor. Keeping L and h fixed is what preserves the creative decisions
    above; doing it here rather than by clipping channels afterwards is what
    keeps the transform smooth enough for a 33^3 LUT to interpolate (a
    per-channel clip at zero is a kink the grid cannot follow).
    """
    Lc, a, b = lab[..., 0], lab[..., 1], lab[..., 2]
    lo = np.zeros_like(Lc)
    hi = np.ones_like(Lc)
    for _ in range(iters):
        mid = 0.5 * (lo + hi)
        lin = oklab_to_linear(np.stack([Lc, a * mid, b * mid], axis=-1))
        ok = lin.min(axis=-1) >= floor
        lo = np.where(ok, mid, lo)
        hi = np.where(ok, hi, mid)
    s = 0.5 * (lo + hi)
    return oklab_to_linear(np.stack([Lc, a * s, b * s], axis=-1))


def grade_display(code, params=P):
    """Creative grade in display-referred space. code: (...,3) Rec.709 g2.4."""
    code = np.asarray(code, dtype=np.float64)
    lin = np.clip(rec709_gamma_decode(code), 0.0, None)
    lab = linear_to_oklab(lin)
    L = np.clip(lab[..., 0], 0.0, 1.0)
    a = lab[..., 1]
    b = lab[..., 2]
    C = np.sqrt(a * a + b * b)
    h = np.arctan2(b, a) % (2.0 * np.pi)
    hd = np.degrees(h)

    # --- 1. lightness ----------------------------------------------------
    L2 = apply_lightness(L, params)

    # --- 2. hue windows --------------------------------------------------
    w_skin = raised_cosine_window(h, np.radians(SKIN_H), np.radians(48.0))
    w_sky = raised_cosine_window(h, np.radians(SKY_H), np.radians(80.0))
    w_fol = raised_cosine_window(h, np.radians(FOLIAGE_H), np.radians(70.0))

    # --- 3. chroma shaping ----------------------------------------------
    mid = smoothstep(0.06, 0.30, L2) * (1.0 - smoothstep(0.72, 0.99, L2))
    boost = params['chroma_mid'] * (
        params['chroma_shadow_keep']
        + (1.0 - params['chroma_shadow_keep']) * smoothstep(0.02, 0.28, L2))
    boost = boost + params['chroma_mid'] * (1.0 - params['chroma_high_fade']) * (
        1.0 - smoothstep(0.72, 0.99, L2)) * 0.0  # reserved hook
    g = 1.0 + boost * (0.35 + 0.65 * mid)

    g = g * (1.0 - (1.0 - params['skin_chroma']) * w_skin)
    g = g * (1.0 + (params['sky_chroma'] - 1.0) * w_sky)
    g = g * (1.0 + (params['foliage_chroma'] - 1.0) * w_fol)

    # pull chroma out of the very top end so highlights keep texture
    g = g * (1.0 - params['highlight_hold'] * smoothstep(0.88, 1.0, L2))
    C2 = np.maximum(C * g, 0.0)

    # --- 4. hue rotations ------------------------------------------------
    # Sky: only rotate where the colour is actually cyan-ish (hue below the
    # sky target), so a true blue is not pushed to violet.
    # Only cyan-leaning sky is pulled toward blue; a colour that is already a
    # true blue is left alone, and the rotation is weighted to the bright,
    # low-chroma part of the frame so water and foliage are not dragged with it.
    sky_pull = smoothstep(params['sky_rot_hi'], params['sky_rot_lo'], hd)
    sky_pull = sky_pull * smoothstep(0.42, 0.62, L2) * (1.0 - smoothstep(0.04, 0.11, C))
    rot = params['sky_rot'] * w_sky * sky_pull
    rot = rot + params['foliage_rot'] * w_fol
    rot = rot + params['skin_rot'] * w_skin
    h2 = h + np.radians(rot)

    # --- 5. warmth -------------------------------------------------------
    w_l = smoothstep(params['warm_lo'], params['warm_hi'], L2)
    w_l = w_l * (1.0 - params['warm_white_fade'] * smoothstep(0.84, 1.0, L2))
    gate = _warm_gate(b, params)
    # An additive tint raises the chroma of an already-coloured surface in
    # proportion to its existing chroma: measured during development, a plain
    # +b offset added 30% chroma to skin and stone, which is the "orange
    # Instagram preset" failure the brief forbids. Damping the offset by
    # existing chroma keeps the honey tint on near-neutral light (walls, haze,
    # highlights) where it reads as sunlight, and leaves coloured surfaces --
    # above all skin -- close to their own colour.
    # Stone, sand and plaster sit at yellow-amber hues (75-90 deg) and should
    # gain warmth; skin sits at orange hues (50-65 deg) and must not. The skin
    # window therefore damps the tint far harder than the chroma damping does,
    # which is what lets the Mediterranean stone glow while the face stays the
    # colour it actually is.
    damp = 1.0 / (1.0 + params['warm_chroma_damp'] * C)
    damp = damp * (1.0 - params['warm_skin_guard'] * w_skin)
    dA = params['warm_a'] * w_l * gate * damp
    dB = params['warm_b'] * w_l * gate * damp

    # a small cool bias in the shadows; deliberately tiny so shadows read as
    # neutral-cool rather than teal
    s_l = (1.0 - smoothstep(0.04, 0.34, L2)) * params['shade_gain']
    dA = dA + params['shade_a'] * s_l
    dB = dB + params['shade_b'] * s_l

    a2 = C2 * np.cos(h2) + dA
    b2 = C2 * np.sin(h2) + dB

    # CHROMA-NEUTRAL WARMTH.
    # Adding a tint to a coloured surface also raises its chroma: measured on
    # the test scenes, the warm offset alone put +12% chroma on skin, on top of
    # the saturation build. Skin that gains chroma reads as sunburnt orange,
    # which the brief forbids. Inside the skin hue window the tint is therefore
    # allowed to change HUE only: the chroma is restored to the value the chroma
    # section designed, leaving the warm direction (honey rather than red) and
    # none of the saturation. Near-neutral pixels keep the full tint, because
    # that is where a warm tint reads as sunlight rather than as colour.
    guard = w_skin * smoothstep(0.008, 0.030, C2)
    if np.any(guard > 0.0):
        Cw = np.hypot(a2, b2)
        hw = np.arctan2(b2, a2)
        Cf = (1.0 - guard) * Cw + guard * C2
        a2 = Cf * np.cos(hw)
        b2 = Cf * np.sin(hw)

    out_lab = np.stack([L2, a2, b2], axis=-1)
    out_lin = gamut_fit_oklab(out_lab)
    out_lin = compress_gamut_out(out_lin)
    return np.clip(rec709_gamma_encode(out_lin), 0.0, 1.0)


# ---------------------------------------------------------------------------
# 4.  FULL PIPELINE
# ---------------------------------------------------------------------------
def full_pipeline(P_in, params=P, creative=True):
    """Apple Log 2 code (AWG) -> Rec.709 gamma 2.4 code."""
    P_in = np.asarray(P_in, dtype=np.float64)
    lin_awg = apple_log_decode(P_in)
    lin709 = apply_matrix(lin_awg, M_AWG_TO_709)
    lin709 = compress_negatives(softpos(lin709, rel=1e-6))
    code = neutral_code(lin709)
    if not creative:
        return code
    return grade_display(code, params)


def build_table(size, params=P, creative=True):
    """Sample the pipeline on a size^3 grid. Red index varies fastest."""
    g = np.linspace(0.0, 1.0, size)
    bb, gg, rr = np.meshgrid(g, g, g, indexing='ij')
    grid = np.stack([rr, gg, bb], axis=-1)
    out = full_pipeline(grid, params, creative)
    return out.reshape(size, size, size, 3)



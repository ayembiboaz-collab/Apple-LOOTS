"""
look.py -- GOLDEN DAYLIGHT CINEMA
=================================

One self-contained transform:

    Apple Log 2 code (Apple Wide Gamut)
      -> Apple Log / Apple Log 2 decode to scene-linear reflectance
      -> Apple Wide Gamut -> Rec.709 matrix (both D65, no adaptation)
      -> negative-channel compression
      -> neutral per-channel filmic tone map  (this is the BEFORE render)
      -> CREATIVE LOOK in OkLab / OkLCh
      -> Rec.709 gamma 2.4 encode

Nothing here assumes the input is already Rec.709 and no second LUT is needed.

Design intent
-------------
The creative grade is built from four separable ideas, none of which is a
global warm filter:

  1. LIGHT     A film-like lightness curve that deepens the midtones, keeps a
               dense but open toe (shadows stay coloured and detailed) and
               compresses the top end so highlight texture survives. Overall
               brightness is *reduced* slightly, because midday footage must
               not be made brighter.
  2. WARMTH    A two-sided split: honey/amber is added to the upper midtones
               and highlights, a very small cool bias to the shadows. The
               warm push is gated so that pixels which are ALREADY strongly
               warm (golden-hour sky, terracotta) receive little of it --
               that is what stops golden-hour footage turning to orange soup.
  3. CHROMA    Perceptual chroma shaping by hue and lightness: rich midtones,
               rolled off in deep shadow and near white, sky blues protected
               from cyan, foliage held to a natural green, skin held DOWN.
  4. HUE       Small hue rotations only where midday light misbehaves: cyan
               sky pulled toward real blue, yellow-green foliage pulled back
               toward green, skin protected from a red/orange rotation.
"""

